#!/usr/bin/env python3
"""Generate compact VS Code-friendly views from the canonical task database."""

from collections import defaultdict
from datetime import datetime
from pathlib import Path

from _env import PROJECT_ROOT
from task_store import open_task_store


OUTPUT_DIR = PROJECT_ROOT / "tasks"


def load_tasks() -> list[dict]:
    store = open_task_store(None, "reporting-reader")
    rows = [
        task for task in store.list()
        if task["status"] not in ("done", "cancelled") and task["external_source"] != "leantime"
    ]
    status_rank = {"in_progress": 0, "blocked": 1}
    rows.sort(key=lambda t: (
        status_rank.get(t["status"], 2),
        t["priority"] is not None, t["priority"] or 0,
        t["due_date"] or "9999-12-31",
        t["id"],
    ))
    columns = ("id", "title", "status", "priority", "project", "due_date", "external_source")
    return [{column: task[column] for column in columns} for task in rows]


def status_label(status: str) -> str:
    return {
        "in_progress": "in progress",
        "blocked": "blocked",
        "todo": "todo",
    }.get(status, status)


def render(title: str, description: str, tasks: list[dict]) -> str:
    generated = datetime.now().strftime("%Y-%m-%d %H:%M")
    lines = [
        f"# {title}",
        "",
        "> Generated from the Tasks API. Do not edit this file;",
        "> use `npx tsx infra/cli.ts tasks ...` and refresh the view afterward.",
        "",
        f"*Generated: {generated}*",
        f"*{description}*",
        "",
    ]

    if not tasks:
        lines.append("_No matching tasks._")
        return "\n".join(lines) + "\n"

    grouped: dict[str, list[dict]] = defaultdict(list)
    for task in tasks:
        grouped[task.get("project") or "Uncategorized"].append(task)

    for project in sorted(grouped):
        lines.extend([f"## {project}", ""])
        for task in grouped[project]:
            due = f" · due {task['due_date']}" if task.get("due_date") else ""
            source = f" · {task['external_source']}" if task.get("external_source") else ""
            lines.append(
                f"- [ ] **#{task['id']} P{task['priority']}** {task['title']}"
                f" — {status_label(task['status'])}{due}{source}"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    tasks = load_tasks()
    active = [
        task
        for task in tasks
        if task["status"] == "in_progress"
        or (task["status"] == "todo" and task["priority"] <= 2)
    ]
    blocked = [task for task in tasks if task["status"] == "blocked"]

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    views = {
        "ACTIVE.md": render(
            "Active Task View",
            "In-progress tasks plus open P1/P2 tasks.",
            active,
        ),
        "BLOCKED.md": render(
            "Blocked Task View",
            "Tasks waiting on a dependency, decision, or external response.",
            blocked,
        ),
    }
    for filename, content in views.items():
        (OUTPUT_DIR / filename).write_text(content, encoding="utf-8")
        print(f"✅ {OUTPUT_DIR / filename}")


if __name__ == "__main__":
    main()
