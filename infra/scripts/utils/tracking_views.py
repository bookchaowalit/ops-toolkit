#!/usr/bin/env python3
"""Generate human-readable goal, habit, and routine views from SQLite.

The database remains the source of truth. This script only reads the canonical
database and rewrites the generated Markdown views under the matching root
workspaces.
"""

from __future__ import annotations

from collections import defaultdict
from datetime import date, datetime, timedelta
import json
from pathlib import Path

from _env import KNOWLEDGE_ROOT, PROJECT_ROOT
from cell_store import open_cell_store
from habits_store import completed_today, open_habits_store


# Tracking views live in the solo-knowledge repository (SOLO_KNOWLEDGE_ROOT).
GOALS_DIR = KNOWLEDGE_ROOT / "goals"
HABITS_DIR = KNOWLEDGE_ROOT / "habits"
ROUTINES_DIR = KNOWLEDGE_ROOT / "routines"


def parse_json_list(value: str | list | None) -> list:
    if not value:
        return []
    if isinstance(value, list):
        return value
    try:
        parsed = json.loads(value)
    except (TypeError, json.JSONDecodeError):
        return []
    return parsed if isinstance(parsed, list) else []


def status_mark(status: str) -> str:
    return {
        "done": "x",
        "completed": "x",
        "blocked": "!",
        "in_progress": "~",
    }.get(status, " ")


def render_goals(generated: str) -> str:
    today = date.today().isoformat()
    store = open_cell_store("goals", "reporting-reader")
    all_goals = store.list("goals")
    all_tasks = store.list("goal-tasks")
    counts_by_goal: dict[int, list[int]] = defaultdict(lambda: [0, 0])
    for task in all_tasks:
        counts = counts_by_goal[task["goal_id"]]
        counts[0] += 1
        counts[1] += 1 if task["status"] == "done" else 0
    goals = [
        {**g, "task_count": counts_by_goal[g["id"]][0], "completed_task_count": counts_by_goal[g["id"]][1]}
        for g in all_goals
        if g["status"] in ("active", "planning")
    ]
    goals.sort(key=lambda g: (g["priority"] is not None, g["priority"] or 0, g["due_date"] or "9999-12-31", g["id"]))

    tasks_by_goal: dict[int, list] = defaultdict(list)
    open_tasks_all = sorted(
        (t for t in all_tasks if t["status"] != "done"),
        key=lambda t: (t["goal_id"], t.get("sort_order") or 0, t["priority"] is not None, t["priority"] or 0, t["id"]),
    )
    for task in open_tasks_all:
        tasks_by_goal[task["goal_id"]].append(task)

    status_counts: dict[str, int] = defaultdict(int)
    for g in all_goals:
        status_counts[g["status"]] += 1
    total_tasks = len(all_tasks)
    completed_tasks = sum(1 for t in all_tasks if t["status"] == "done")

    lines = [
        "# Active Goal View",
        "",
        "> Generated from the goals and habits cells. Do not edit this file;",
        "> use `goals-cli.py` or the database-backed CLI, then refresh the view.",
        "",
        f"*Generated: {generated}*",
        f"*As of: {today}*",
        "",
        "## Summary",
        "",
        f"- Active/planning goals: **{len(goals)}**",
        f"- All goals: **{sum(status_counts.values())}**",
        f"- Goal milestones: **{completed_tasks}/{total_tasks}** completed",
        f"- Paused goals: **{status_counts.get('paused', 0)}**",
        "",
    ]

    if not goals:
        lines.append("_No active or planning goals._")
        return "\n".join(lines) + "\n"

    for goal in goals:
        progress = goal["progress_percent"] or 0
        due = f" · due {goal['due_date']}" if goal["due_date"] else ""
        category = goal["category"] or "general"
        goal_type = goal["type"] or "unspecified"
        lines.extend(
            [
                f"## 🎯 #{goal['id']} {goal['title']}",
                "",
                f"- **Status:** `{goal['status']}` · **Priority:** P{goal['priority']}"
                f" · **Type:** {goal_type} · **Category:** {category}",
                f"- **Progress:** {progress}% · **Milestones:** "
                f"{goal['completed_task_count']}/{goal['task_count']}{due}",
            ]
        )
        if goal["description"]:
            lines.append(f"- **Description:** {goal['description']}")

        open_tasks = tasks_by_goal.get(goal["id"], [])
        if open_tasks:
            lines.extend(["", "### Open milestones", ""])
            for task in open_tasks:
                due = f" · due {task['due_date']}" if task["due_date"] else ""
                priority = task["priority"] or "-"
                mark = status_mark(task["status"])
                lines.append(
                    f"- [{mark}] {task['title']} — `{task['status']}` · "
                    f"priority {priority}{due}"
                )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def render_overdue_goals(generated: str) -> str:
    """Render open milestones that are overdue for active/planning goals."""
    today = date.today().isoformat()
    store = open_cell_store("goals", "reporting-reader")
    goals_by_id = {g["id"]: g for g in store.list("goals", status=["active", "planning"])}
    overdue = []
    for gt in store.list("goal-tasks"):
        goal = goals_by_id.get(gt["goal_id"])
        due = str(gt["due_date"])[:10] if gt.get("due_date") else None
        if goal is None or gt["status"] in ("done", "cancelled") or not due or due >= today:
            continue
        overdue.append(
            {
                "goal_id": goal["id"], "goal_title": goal["title"], "goal_status": goal["status"],
                "task_id": gt["id"], "task_title": gt["title"], "task_status": gt["status"],
                "priority": gt["priority"], "due_date": due,
                "days_overdue": (date.fromisoformat(today) - date.fromisoformat(due)).days,
                "_goal_priority": goal["priority"] or 0,
            }
        )
    overdue.sort(key=lambda r: (r["due_date"], r["_goal_priority"], r["priority"] or 0, r["task_id"]))

    lines = [
        "# Overdue Goal Milestones",
        "",
        "> Generated from the goals and habits cells. Do not edit this file;",
        "> review and update milestones with `goals-cli.py` or the database-backed CLI.",
        "",
        f"*Generated: {generated}*",
        f"*As of: {today}*",
        "",
        "## Summary",
        "",
        f"- Open overdue milestones: **{len(overdue)}**",
        f"- Goals affected: **{len({row['goal_id'] for row in overdue})}**",
        "",
    ]

    if not overdue:
        lines.append("_No overdue milestones for active or planning goals._")
        return "\n".join(lines) + "\n"

    lines.extend(["## Review queue", ""])
    for task in overdue:
        priority = task["priority"] or "-"
        days = task["days_overdue"] or 0
        lines.append(
            f"- [ ] **Goal #{task['goal_id']}: {task['goal_title']}** — "
            f"milestone #{task['task_id']} {task['task_title']} · "
            f"`{task['task_status']}` · priority {priority} · "
            f"due {task['due_date']} ({days} days overdue)"
        )

    return "\n".join(lines).rstrip() + "\n"


def habit_is_scheduled(habit, today: date) -> bool:
    schedule_days = parse_json_list(habit["schedule_days"])
    return not schedule_days or today.strftime("%a").lower()[:3] in schedule_days


def render_habits(generated: str) -> str:
    today = date.today()
    today_str = today.isoformat()
    store = open_habits_store("reporting-reader")
    done_ids = completed_today(store.habit_logs(date_from=today_str, date_to=today_str), today_str)
    habits = [{**h, "done_today": h["id"] in done_ids} for h in store.habits(status="active")]
    # ORDER BY priority, preferred_time, id (NULLs first, as in SQLite)
    habits.sort(
        key=lambda h: (
            h.get("priority") is not None, h.get("priority") or 0,
            h.get("preferred_time") is not None, h.get("preferred_time") or "",
            h["id"],
        )
    )
    scheduled = [habit for habit in habits if habit_is_scheduled(habit, today)]
    done_today = sum(1 for habit in scheduled if habit["done_today"])
    week_start = (today - timedelta(days=6)).isoformat()
    week_logs = len(store.habit_logs(date_from=week_start, date_to=today_str, completed=True))

    lines = [
        "# Active Habit View",
        "",
        "> Generated from the goals and habits cells. Do not edit this file;",
        "> use the habit CLI to log completion, then refresh the view.",
        "",
        f"*Generated: {generated}*",
        f"*Today: {today.strftime('%Y-%m-%d (%A)')}*",
        "",
        "## Summary",
        "",
        f"- Scheduled today: **{done_today}/{len(scheduled)}** completed",
        f"- Active habits: **{len(habits)}**",
        f"- Completions in the last 7 days: **{week_logs}**",
        "",
    ]

    if not habits:
        lines.append("_No active habits._")
        return "\n".join(lines) + "\n"

    lines.extend(["## Habits", ""])
    for habit in habits:
        mark = "x" if habit["done_today"] else " "
        target = f" · {habit['target_duration_minutes']} min" if habit["target_duration_minutes"] else ""
        time = f" · {habit['preferred_time']}" if habit["preferred_time"] else ""
        streak = f" · streak {habit['current_streak'] or 0} (best {habit['best_streak'] or 0})"
        schedule = ", ".join(parse_json_list(habit["schedule_days"]))
        schedule_text = f" · days: {schedule}" if schedule else ""
        lines.append(
            f"- [{mark}] **#{habit['id']} {habit['name']}** — {habit['category']} · "
            f"{habit['frequency']}{target}{time}{schedule_text}{streak}"
        )
    return "\n".join(lines).rstrip() + "\n"


def routine_step_count(value: str | list | None) -> int:
    return len(parse_json_list(value))


def render_routines(generated: str) -> str:
    today_str = date.today().isoformat()
    store = open_habits_store("reporting-reader")
    today_logged = {log["routine_id"] for log in store.routine_logs(date_from=today_str, date_to=today_str)}
    routines = [
        {**r, "done_today": r["id"] in today_logged}
        for r in sorted(store.routines(status="active"), key=lambda r: r["id"])
    ]
    routine_names = {r["id"]: r["name"] for r in store.routines()}
    recent_logs = [
        {**log, "name": routine_names[log["routine_id"]]}
        for log in store.routine_logs(order="desc")
        if log["routine_id"] in routine_names
    ][:7]
    done_today = sum(1 for routine in routines if routine["done_today"])

    lines = [
        "# Active Routine View",
        "",
        "> Generated from the goals and habits cells. Do not edit this file;",
        "> use `routines-cli.py` to log completion, then refresh the view.",
        "",
        f"*Generated: {generated}*",
        f"*Today: {today_str}*",
        "",
        "## Summary",
        "",
        f"- Completed today: **{done_today}/{len(routines)}**",
        f"- Active routines: **{len(routines)}**",
        "",
    ]

    if not routines:
        lines.append("_No active routines._")
    else:
        lines.extend(["## Routines", ""])
        for routine in routines:
            mark = "x" if routine["done_today"] else " "
            duration = routine["total_duration_minutes"] or 0
            steps = routine_step_count(routine["steps"])
            lines.append(
                f"- [{mark}] **#{routine['id']} {routine['name']}** — "
                f"{routine['routine_type']} · {steps} steps · ~{duration} min"
            )

    if recent_logs:
        lines.extend(["", "## Recent logs", ""])
        for log in recent_logs:
            duration = f" · {log['duration_minutes']} min" if log["duration_minutes"] else ""
            lines.append(f"- {log['log_date']} — {log['name']}{duration}")

    return "\n".join(lines).rstrip() + "\n"


def refresh_views() -> tuple[Path, ...]:
    """Regenerate all tracked goal, habit, and routine Markdown views."""
    generated = datetime.now().strftime("%Y-%m-%d %H:%M")
    views = {
        GOALS_DIR / "ACTIVE.md": render_goals(generated),
        GOALS_DIR / "OVERDUE.md": render_overdue_goals(generated),
        HABITS_DIR / "ACTIVE.md": render_habits(generated),
        ROUTINES_DIR / "ACTIVE.md": render_routines(generated),
    }

    for path, content in views.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return tuple(views)


def main() -> None:
    for path in refresh_views():
        print(f"✅ {path}")


if __name__ == "__main__":
    main()
